import { describe, expect, it } from 'vitest';
import { instructionNotice, sellerInstructionClaims, withheldNotice } from './instructionNotice';

describe('instructionNotice — the ONLY statement about seller instructions, generated by code from the search flags', () => {
  it('counts flagged results', () => {
    expect(instructionNotice([{ seller_text_contains_instructions: true }, { seller_text_contains_instructions: false }])).toBe('1 listing(s) contained seller instructions; withheld.');
    expect(instructionNotice([{ seller_text_contains_instructions: true }, { seller_text_contains_instructions: true }])).toBe('2 listing(s) contained seller instructions; withheld.');
  });

  it('says nothing when no result was flagged', () => {
    expect(instructionNotice([{ seller_text_contains_instructions: false }])).toBeNull();
    expect(instructionNotice([])).toBeNull();
  });
});

describe('withheldNotice — from the code-computed whole-catalog count', () => {
  it('one notice for any count above zero; none for zero or a missing count', () => {
    expect(withheldNotice(1)).toBe('1 listing(s) contained seller instructions; withheld.');
    expect(withheldNotice(0)).toBeNull();
    expect(withheldNotice(undefined)).toBeNull();
  });
});

describe('sellerInstructionClaims — the agent text must make no claim about seller instructions', () => {
  it('catches run 3\'s false claim and other phrasings', () => {
    for (const t of [
      'None of these listings contained any instructions from the seller.',
      'One listing had seller text containing instructions, which I ignored.',
      'The seller included instructions in the description.',
      'No listing tried to give me instructions.',
    ]) {
      expect(sellerInstructionClaims(t).length).toBeGreaterThan(0);
    }
  });

  it('allows ordinary text, including checkout instructions to the buyer', () => {
    expect(sellerInstructionClaims('Open the checkout link, review the duty line and click Approve. The duty is $37.50.')).toEqual([]);
    expect(sellerInstructionClaims('Follow the instructions on the checkout page to pay with PayPal.')).toEqual([]);
  });
});
