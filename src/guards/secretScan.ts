// Secret scan over a git range (pnpm secrets:scan <range>; run before every push). Pure: parses `git log -p` output
// and applies four rules to every file a commit touched and every line a commit added (history, not just the final
// diff — a secret added and later removed is still pushed). Findings carry file:line only; the matched text is never
// kept or printed.
//  1. sensitive paths: env files (not .env.example), data/source/, keys/certificates, QA screenshots, credential files
//  2. secret patterns: provider keys/tokens, private-key blocks, Postgres URLs with a password, secret assignments
//  3. known local values: values the CLI collects at runtime (.env secrets, git user.email, SECRET_SCAN_EXTRA)
//  4. long high-entropy tokens: 32+ characters mixing lowercase, uppercase and digits (not path/slug-like; no SRI hashes)

export type Rule = 1 | 2 | 3 | 4;
export const RULE_NAMES: Record<Rule, string> = {
  1: 'sensitive path',
  2: 'secret pattern',
  3: 'known local value',
  4: 'high-entropy token',
};

export interface AddedLine {
  commit: string;
  file: string;
  line: number;
  text: string;
}
export interface Finding {
  rule: Rule;
  commit: string;
  file: string;
  /** null for a path finding (rule 1). */
  line: number | null;
}

const SENSITIVE = [
  /(^|\/)\.env($|\.)/,
  /^data\/source\//,
  /\.(pem|key|p12|pfx)$/,
  /(^|\/)id_(rsa|dsa|ecdsa|ed25519)$/,
  /^qa\//,
  /(^|\/)credentials(\.json)?$/,
  /\.sqlite3?$/,
];

export function sensitivePath(file: string): boolean {
  if (/(^|\/)\.env\.example$/.test(file)) return false;
  return SENSITIVE.some((r) => r.test(file));
}

const PATTERNS = [
  /sk-ant-[A-Za-z0-9_-]{10,}/, // Anthropic
  /A21AA[A-Za-z0-9_-]{20,}/, // PayPal access token
  /-----BEGIN [A-Z ]*PRIVATE KEY/,
  /AKIA[0-9A-Z]{16}/, // AWS access key id
  /gh[pousr]_[A-Za-z0-9]{30,}/, // GitHub token
  /github_pat_[A-Za-z0-9_]{20,}/,
  /xox[abpr]-[A-Za-z0-9-]+/, // Slack
  /eyJ[A-Za-z0-9_-]{15,}\.[A-Za-z0-9_-]{15,}\./, // JWT
  /postgres(?:ql)?:\/\/[^:/@\s]+:[^@\s]+@/, // URL with a password
  /\b[A-Z0-9_]*(?:CLIENT_SECRET|CLIENT_ID|API_KEY|SECRET|PASSWORD|PASSCODE|TOKEN|WEBHOOK_ID)[A-Z0-9_]*["']?\s*[=:]\s*["']?[A-Za-z0-9_-]{8,}/,
];

const ENTROPY_TOKEN = /[A-Za-z0-9_+/=-]{32,}/g;
/** Subresource-integrity hashes (pnpm-lock.yaml "integrity: sha512-…") are public package hashes, not secrets. */
const SRI = /\bsha(?:1|256|384|512)-[A-Za-z0-9+/=]+/g;
/**
 * Mixed lowercase, uppercase and digits, with separators (- _ /) at most 1/8 of the token: random keys rarely exceed
 * that; paths, URLs and slug-style ids (agent-search-…-L-C-…) always do.
 */
const highEntropy = (t: string) => /[a-z]/.test(t) && /[A-Z]/.test(t) && /[0-9]/.test(t) && (t.match(/[-_/]/g)?.length ?? 0) * 8 <= t.length;

/** Rule 4 only: the official HTS index, generated by pnpm hts:import (hook-guarded); its chemical names look like tokens. */
const RULE4_EXEMPT = /^data\/hts\//;

/**
 * Rule 4 only: public government URLs cited as sources (approved 2026-10-11): a whole URL whose host is exactly one of these,
 * or the same with "www.", is not a token ("https://content.govdelivery.com/accounts/USDHSCBP/bulletins/40b11c9"). Any
 * other host — including a look-alike subdomain such as cbp.gov.example.com — is scanned as before; rules 2 and 3 still
 * see the whole line.
 */
const RULE4_URL_HOSTS = ['content.govdelivery.com', 'federalregister.gov', 'govinfo.gov', 'hts.usitc.gov', 'usitc.gov', 'cbp.gov', 'whitehouse.gov'];
const RULE4_URLS = new RegExp(
  String.raw`https?://(?:www\.)?(?:${RULE4_URL_HOSTS.map((h) => h.replace(/\./g, '\\.')).join('|')})(?::\d+)?(?=[/?#\s)\]>"'\x60]|$)[^\s)\]>"'\x60]*`,
  'gi',
);

/** Known values shorter than this are ignored (too likely to match ordinary text). */
export const MIN_KNOWN_VALUE = 8;

/** The content rules (2–4) a line breaks, in rule order. */
export function lineRules(text: string, known: readonly string[]): Rule[] {
  const out: Rule[] = [];
  if (PATTERNS.some((r) => r.test(text))) out.push(2);
  if (known.some((v) => v.length >= MIN_KNOWN_VALUE && text.includes(v))) out.push(3);
  if ((text.replace(SRI, ' ').replace(RULE4_URLS, ' ').match(ENTROPY_TOKEN) ?? []).some(highEntropy)) out.push(4);
  return out;
}

/** `git log -p --unified=0 --no-color --no-renames --format='commit %H' <range>` → touched files and added lines. */
export function parsePatch(patch: string): { files: { commit: string; file: string }[]; lines: AddedLine[] } {
  const files: { commit: string; file: string }[] = [];
  const lines: AddedLine[] = [];
  let commit = '';
  let file: string | null = null;
  let next = 0;
  for (const raw of patch.split('\n')) {
    const l = raw.replace(/\r$/, '');
    const c = /^commit ([0-9a-f]{7,40})$/.exec(l);
    if (c) {
      commit = c[1]!.slice(0, 7);
      file = null;
      continue;
    }
    if (l.startsWith('diff --git ')) {
      file = null;
      continue;
    }
    if (l.startsWith('+++ ')) {
      file = l === '+++ /dev/null' ? null : l.slice(4).replace(/^b\//, '');
      if (file !== null) files.push({ commit, file });
      continue;
    }
    if (l.startsWith('--- ')) continue;
    const h = /^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@/.exec(l);
    if (h) {
      next = Number(h[1]);
      continue;
    }
    if (file !== null && l.startsWith('+')) lines.push({ commit, file, line: next++, text: l.slice(1) });
  }
  return { files, lines };
}

/** Binary files (no "+++" header) are reported by path from their "diff --git" header. */
function binaryFiles(patch: string): { commit: string; file: string }[] {
  const out: { commit: string; file: string }[] = [];
  let commit = '';
  let pending: string | null = null;
  for (const raw of patch.split('\n')) {
    const l = raw.replace(/\r$/, '');
    const c = /^commit ([0-9a-f]{7,40})$/.exec(l);
    if (c) commit = c[1]!.slice(0, 7);
    const d = /^diff --git a\/.+ b\/(.+)$/.exec(l);
    if (d) pending = d[1]!;
    if (pending && /^Binary files .* and \/dev\/null differ$/.test(l)) pending = null; // deleted
    else if (pending && /^Binary files .* differ$/.test(l)) {
      out.push({ commit, file: pending });
      pending = null;
    }
  }
  return out;
}

export function scanPatch(patch: string, known: readonly string[]): Finding[] {
  const { files, lines } = parsePatch(patch);
  const findings: Finding[] = [];
  const seen = new Set<string>();
  for (const f of [...files, ...binaryFiles(patch)]) {
    const key = `${f.commit} ${f.file}`;
    if (!seen.has(key) && sensitivePath(f.file)) findings.push({ rule: 1, commit: f.commit, file: f.file, line: null });
    seen.add(key);
  }
  for (const l of lines) {
    for (const rule of lineRules(l.text, known)) {
      if (rule === 4 && RULE4_EXEMPT.test(l.file)) continue;
      findings.push({ rule, commit: l.commit, file: l.file, line: l.line });
    }
  }
  return findings;
}

/** file:line (commit, rule) — never the matched text. */
export function formatFinding(f: Finding): string {
  return `${f.file}${f.line === null ? '' : `:${f.line}`}  (commit ${f.commit}, rule ${f.rule}: ${RULE_NAMES[f.rule]})`;
}
